// Builds the site from the numbered folders in assets/images/.
//
//   node tools/build.mjs
//
// For each folder, e.g. 101-cosa:
//   1. renames the photographs to 101-00.jpg (the cover: whichever file's name
//      starts with "00"), then 101-01.jpg, 101-02.jpg … Photographs already
//      named this way keep their order; new ones are added after them, in the
//      order Finder lists them by name.
//   2. makes the sizes the pages use (101-01-960.avif, …-960.webp, one .jpg),
//      skipping any already made from the current file, and deletes sizes
//      whose photograph is gone.
// Then it writes the pages:
//   projects.html, one page per project, studies.html — entirely
//   the menu in every page, and the hero in index.html — between markers.
// Everything else in index.html and about.html is hand-written and left alone.

import fs from "node:fs/promises";
import crypto from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { site, sections, names, meta, alt, hidden, widths, fallbackWidth, encode } from "./config.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IMAGES = path.join(ROOT, "assets/images");
const GENERATED = "<!-- Generated by tools/build.mjs — change the build or the folders, not this file. -->";
const PROJECT_MARK = "<!-- generated project page -->";

// Several sizes are made at once; each one on a single thread.
sharp.concurrency(1);
const PARALLEL = 4;

// BUILD_SECONDS=150 node tools/build.mjs stops starting new work after 150
// seconds and leaves the pages alone; running it again carries on where it
// stopped. Without it the build simply runs to the end.
const DEADLINE = process.env.BUILD_SECONDS ? Date.now() + Number(process.env.BUILD_SECONDS) * 1000 : Infinity;
class OutOfTime extends Error {}

// Which version of each photograph its sizes were made from, by content — a
// checkout on GitHub gives every file a new date, so dates cannot be trusted.
const CACHE_FILE = path.join(ROOT, "tools/image-cache.json");
const cache = JSON.parse(await fs.readFile(CACHE_FILE, "utf8").catch(() => "{}"));
const SETTINGS = JSON.stringify({ widths, fallbackWidth, encode });
// Every version ever recorded. A photograph that moved folder or number
// arrives under a new name, but if its content matches a recorded version,
// the sizes that moved with it are the ones made from it.
const known = new Set(Object.values(cache));
const saveCache = () => fs.writeFile(CACHE_FILE, JSON.stringify(cache, null, 1) + "\n");

async function pool(tasks, n) {
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => {
    while (i < tasks.length) await tasks[i++]();
  }));
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const log = (...a) => console.log(...a);

// Finder's order: case ignored, runs of digits compared as numbers, digits first.
function natural(a, b) {
  const ax = a.toLowerCase().match(/\d+|\D+/g) || [];
  const bx = b.toLowerCase().match(/\d+|\D+/g) || [];
  for (let i = 0; i < Math.min(ax.length, bx.length); i++) {
    const x = ax[i], y = bx[i];
    if (x === y) continue;
    const nx = /^\d/.test(x), ny = /^\d/.test(y);
    if (nx && ny) return Number(x) - Number(y) || x.length - y.length;
    if (nx !== ny) return nx ? -1 : 1;
    return x < y ? -1 : 1;
  }
  return ax.length - bx.length;
}

const SMALL = new Set(["a", "an", "and", "the", "of", "in", "on", "at", "to", "for"]);
function nameFor(slug) {
  if (names[slug]) return names[slug];
  return slug.split("-").map((w, i) => (i > 0 && SMALL.has(w) ? w : w.charAt(0).toUpperCase() + w.slice(1))).join(" ");
}

const exists = (p) => fs.stat(p).then((s) => s, () => null);

// ------------------------------------------------------------- folders ----
async function findGroups() {
  const groups = [];
  for (const entry of (await fs.readdir(IMAGES, { withFileTypes: true })).sort((a, b) => natural(a.name, b.name))) {
    if (!entry.isDirectory()) continue;
    let dir = entry.name;
    if (dir !== dir.toLowerCase()) {
      // Web addresses are case-sensitive; keep every folder lowercase.
      await fs.rename(path.join(IMAGES, dir), path.join(IMAGES, dir + ".tmp-case"));
      await fs.rename(path.join(IMAGES, dir + ".tmp-case"), path.join(IMAGES, dir.toLowerCase()));
      log(`renamed folder ${dir} → ${dir.toLowerCase()}`);
      dir = dir.toLowerCase();
    }
    const m = dir.match(/^(\d)(\d\d)-([a-z0-9-]+)$/);
    if (!m) { log(`skipped folder ${dir}: not named like 101-name`); continue; }
    const section = Number(m[1]);
    if (!sections[section]) { log(`skipped folder ${dir}: no section ${section}xx`); continue; }
    if (hidden.includes(m[3])) { log(`skipped folder ${dir}: hidden in tools/config.mjs`); continue; }
    groups.push({ dir, code: m[1] + m[2], section, slug: m[3], name: nameFor(m[3]), photos: [], cover: null });
  }
  return groups;
}

// ----------------------------------------------------- rename + resize ----
const ORIGINAL = /\.(jpe?g|png|tiff?|webp|heic)$/i;

async function processGroup(g) {
  const dir = path.join(IMAGES, g.dir);
  let files = (await fs.readdir(dir)).filter((f) => !f.startsWith("."));
  for (const f of files.filter((f) => f.endsWith(".tmp"))) await fs.unlink(path.join(dir, f));
  files = files.filter((f) => !f.endsWith(".tmp"));

  // A made size is "<photo>-<width>.<ext>" next to its photograph.
  const stemsOf = (list) => new Set(list.filter((f) => /\.jpe?g$/i.test(f)).map((f) => f.replace(/\.[^.]+$/, "").toLowerCase()));
  let stems = stemsOf(files);
  const isSize = (f) => {
    const m = f.match(/^(.*)-(\d{3,4})\.(avif|webp|jpe?g)$/i);
    return !!m && (stems.has(m[1].toLowerCase()) || /^\d{3}-\d\d$/.test(m[1]));
  };
  const sizes = files.filter(isSize);
  const originals = files.filter((f) => ORIGINAL.test(f) && !isSize(f));

  // The cover is the first file whose name starts with "00" — or with any
  // code and then 00, so a cover moved in from another folder stays a cover.
  const stem = (f) => f.replace(/\.[^.]+$/, "");
  const coverRe = /^(\d{3}-)?00(?!\d)/i;
  const cover = originals.filter((f) => coverRe.test(stem(f))).sort(natural)[0] || null;
  const rest = originals.filter((f) => f !== cover);
  const canonical = new RegExp(`^${g.code}-(\\d\\d)\\.jpg$`);
  const kept = rest.filter((f) => canonical.test(f)).sort(natural);
  const added = rest.filter((f) => !canonical.test(f)).sort(natural);

  const plan = [];
  if (cover) plan.push({ from: cover, to: `${g.code}-00.jpg` });
  [...kept, ...added].forEach((f, i) => plan.push({ from: f, to: `${g.code}-${String(i + 1).padStart(2, "0")}.jpg` }));

  // Two steps, through temporary names, so no rename lands on a file still
  // waiting to move. A photograph's sizes move with it, so nothing has to be
  // made again just because a photograph was renumbered or changed folder.
  const moving = plan.filter((p) => p.from !== p.to);
  for (const [i, p] of moving.entries()) {
    p.tmp = `rename-${i}.tmp`;
    await fs.rename(path.join(dir, p.from), path.join(dir, p.tmp));
    const prefix = stem(p.from);
    p.sizes = sizes
      .filter((f) => f.slice(0, prefix.length).toLowerCase() === prefix.toLowerCase() && /^-\d{3,4}\.(avif|webp|jpe?g)$/i.test(f.slice(prefix.length)))
      .map((f, j) => ({ file: f, suffix: f.slice(prefix.length).toLowerCase().replace(/\.jpeg$/, ".jpg"), tmp: `rename-${i}-${j}.tmp` }));
    for (const sz of p.sizes) await fs.rename(path.join(dir, sz.file), path.join(dir, sz.tmp));
  }
  for (const p of moving) {
    for (const sz of p.sizes) await fs.rename(path.join(dir, sz.tmp), path.join(dir, stem(p.to) + sz.suffix));
    const target = path.join(dir, p.to);
    if (/\.jpe?g$/i.test(p.from)) {
      await fs.rename(path.join(dir, p.tmp), target);
    } else {
      await sharp(path.join(dir, p.tmp)).jpeg({ quality: 95 }).toFile(target);
      await fs.unlink(path.join(dir, p.tmp));
    }
    log(`  ${g.dir}: ${p.from} → ${p.to}`);
  }

  // Sizes.
  const wanted = new Set();
  for (const p of plan) {
    const src = path.join(dir, p.to);
    const base = p.to.replace(/\.jpg$/, "");
    const info = await sharp(src).metadata();
    let [w, h] = [info.width, info.height];
    if ((info.orientation || 1) >= 5) [w, h] = [h, w];
    const ws = widths.filter((x) => x < w);
    if (w <= widths[widths.length - 1]) ws.push(w);
    if (!ws.length) ws.push(w);
    const jpg = ws.filter((x) => x <= fallbackWidth).pop() || ws[0];
    const srcTime = (await fs.stat(src)).mtimeMs;
    const hash = crypto.createHash("sha1").update(await fs.readFile(src)).update(SETTINGS).digest("hex").slice(0, 16);
    const key = `${g.dir}/${base}`;
    const jobs = [...ws.flatMap((x) => [[x, "avif"], [x, "webp"]]), [jpg, "jpg"]];
    const todo = [];
    for (const [x, ext] of jobs) {
      const name = `${base}-${x}.${ext}`;
      wanted.add(name);
      const out = path.join(dir, name);
      const have = await exists(out);
      // Up to date if made from this exact file — or, for a photograph the
      // record has never seen, if the size is newer than the photograph.
      if (have && (known.has(hash) || (!cache[key] && have.mtimeMs >= srcTime))) continue;
      todo.push(async () => {
        if (Date.now() > DEADLINE) throw new OutOfTime();
        let pipe = sharp(src).rotate().resize({ width: x, withoutEnlargement: true });
        pipe = ext === "avif" ? pipe.avif(encode.avif) : ext === "webp" ? pipe.webp(encode.webp) : pipe.jpeg(encode.jpeg);
        await pipe.toFile(out + ".tmp");
        await fs.rename(out + ".tmp", out);
        log(`  made ${name}`);
      });
    }
    await pool(todo, PARALLEL);
    cache[key] = hash;
    // A portrait photograph is shown in a 3:4 frame, filled and centred, so
    // every portrait on the site has the same shape whatever it was shot at.
    // Squares and landscapes keep their own shape.
    const photo = { base: `assets/images/${g.dir}/${base}`, key: base, w, h, widths: ws, jpg, tall: w / h < 0.95 };
    if (p.to.endsWith("-00.jpg")) g.cover = photo; else g.photos.push(photo);
  }
  // Sizes left over from photographs that have gone (looked up again, now
  // that the renames are done).
  const now = (await fs.readdir(dir)).filter((f) => !f.startsWith("."));
  stems = stemsOf(now);
  for (const f of now.filter(isSize)) {
    if (!wanted.has(f)) { await fs.unlink(path.join(dir, f)); log(`  removed old size ${g.dir}/${f}`); }
  }
  for (const k of Object.keys(cache)) {
    if (k.startsWith(g.dir + "/") && !plan.some((p) => k === `${g.dir}/${p.to.replace(/\.jpg$/, "")}`)) delete cache[k];
  }
  g.photos.forEach((p, i) => { p.alt = alt[p.key] ?? `${g.name}, photograph ${i + 1}`; });
  if (g.cover) g.cover.alt = alt[g.cover.key] ?? g.name;
}

// --------------------------------------------------------------- pages ----
const srcset = (p, ext) => p.widths.map((w) => `${p.base}-${w}.${ext} ${w}w`).join(", ");
function picture(p, { cls = "", style = "", sizes, imgClass = "", lazy = false, indent = "      " }) {
  const c = cls ? ` class="${cls}"` : "";
  const s = style ? ` style="${style}"` : "";
  const ic = imgClass ? ` class="${imgClass}"` : "";
  return [
    `${indent}<picture${c}${s}>`,
    `${indent}  <source type="image/avif" srcset="${srcset(p, "avif")}" sizes="${sizes}">`,
    `${indent}  <source type="image/webp" srcset="${srcset(p, "webp")}" sizes="${sizes}">`,
    `${indent}  <img${ic} src="${p.base}-${p.jpg}.jpg" width="${p.w}" height="${p.h}" alt="${esc(p.alt)}"${lazy ? ' loading="lazy"' : ""} decoding="async">`,
    `${indent}</picture>`,
  ].join("\n");
}
const ratio = (p) => (p.tall ? 0.75 : +(p.w / p.h).toFixed(4));

function navBlock(groups, kind, current) {
  const projects = groups.filter((g) => g.section === 1);
  const fleeting = groups.filter((g) => g.section === 2);
  const top = (label, href, here, extra = "") =>
    `<a class="nav-top${here ? " here" : ""}" href="${href}"${extra}${here ? ' aria-current="page"' : ""}>${label}</a>`;
  const L = [
    "      <!-- nav start — written by tools/build.mjs from the folders in assets/images/.",
    "           The section you are in shows the pages under it; on an upright phone",
    "           a tap opens a section sideways (nav.js). -->",
    '      <div class="side-nav" id="nav">',
    `        <div class="nav-group${kind === "projects" || kind === "project" ? " open" : ""}">`,
    "          " + (sections[1].index === false
      // Not a page of its own: a button that opens the list (nav.js, for touch screens).
      ? `<button class="nav-top" type="button" aria-expanded="${kind === "project"}">Projects</button>`
      : top("Projects", sections[1].page, kind === "projects", kind === "projects" ? ' data-p="*"' : "")),
    '          <div class="nav-sub"><div>',
    ...projects.map((g) => {
      const on = kind === "project" && current === g.slug ? ' class="on" aria-current="page"' : "";
      const dp = kind === "projects" ? ` data-p="${g.slug}"` : "";
      return `            <a${on} href="${g.slug}.html"${dp}>${esc(g.name)}</a>`;
    }),
    "          </div></div>",
    "        </div>",
    `        <div class="nav-group${kind === "fleeting" ? " open" : ""}">`,
    "          " + top(sections[2].title, sections[2].page, kind === "fleeting", kind === "fleeting" ? ' data-g="*"' : ""),
    '          <div class="nav-sub"><div>',
    ...fleeting.map((g) =>
      kind === "fleeting"
        ? `            <a href="#${g.slug}" data-g="${g.slug}">${esc(g.name)}</a>`
        : `            <a href="${sections[2].page}#${g.slug}">${esc(g.name)}</a>`),
    "          </div></div>",
    "        </div>",
    // Shop is hidden for now: shop.html and assets/shop/ are kept and still
    // built, but nothing in the menu links to them. To show it again, put
    // these three lines back here:
    //   '        <div class="nav-group">',
    //   "          " + top("Shop", "shop.html", kind === "shop"),
    //   "        </div>",
    '        <div class="nav-group">',
    "          " + top("About", "about.html", kind === "about"),
    "        </div>",
    "      </div>",
    "      <!-- nav end -->",
    "",
  ];
  return L.join("\n");
}

