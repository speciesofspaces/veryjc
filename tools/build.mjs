const placeholder = (label, r = "4/5", cls = "") =>
  `<div class="${cls ? cls + " " : ""}ph" style="--r:${r}"><span>${esc(label)}</span></div>`;

function projectsPage(groups) {
  const projects = groups.filter((g) => g.section === 1);
  // One cover per project (its -00 photograph, or its first if it has none),
  // all in one row at one height: each cover is as wide as its shape needs
  // and together they fill the width.
  const covers = projects.map((g) => {
    const pic = g.cover || g.photos[0];
    const n = g.photos.length;
    // The line beside the name is the one from tools/config.mjs → meta; no count.
    const line = meta[g.slug] || (n ? "" : "Photographs to come");
    const img = pic
      ? picture(pic, { imgClass: "cover-img", sizes: "(max-width: 820px) 50vw, 35vw", indent: "        " })
      : "        " + placeholder("Cover to come", "0.75", "cover-img");
    return [
      `      <a class="cover" href="${g.slug}.html" style="--r:${pic ? ratio(pic) : 0.75}">`,
      img,
      `        <span class="cover-cap"><span class="t">${esc(g.name)}</span>${line ? `<span class="m">${esc(line)}</span>` : ""}</span>`,
      "      </a>",
    ].join("\n");
  });
  return shell({
    title: `Projects — ${site.name}`, desc: `Projects — photographs by ${site.name}.`, bodyClass: "projects-page",
    nav: navBlock(groups, "projects"), noindex: sections[1].index === false,
    main: `    <!-- One cover per project, in one row at one height. -->
    <div class="wall-window">
    <div class="covers">
${covers.join("\n")}
    </div>
    </div>`,
  });
}

function projectPage(groups, g) {
  const plates = g.photos.length
    ? g.photos.map((p, i) => picture(p, { cls: `plate${p.tall ? " tall" : ""}${i === 0 ? " on" : ""}`, style: `--r:${p.tall ? "3/4" : `${p.w}/${p.h}`};--k:${i}`, sizes: "(max-width: 820px) 92vw, 80vh", lazy: i > 0 }))
    : ["      " + placeholder("Photographs to come", "4/5", "plate on")];
  return shell({
    title: `${g.name} — ${site.name}`, desc: `${g.name} — photographs by ${site.name}.`, bodyClass: "project-page",
    counter: true, nav: navBlock(groups, "project", g.slug), scripts: ["viewer.js"], marker: PROJECT_MARK,
    main: `    <!-- ${g.dir}: one photograph at a time; its halves step back and forward. -->
    <div class="viewer" id="viewer" aria-roledescription="image viewer" aria-label="${esc(g.name)}">
${plates.join("\n")}
      <button class="zone prev" type="button" aria-label="Previous photograph"></button>
      <button class="zone next" type="button" aria-label="Next photograph"></button>
    </div>`,
  });
}

function fleetingPage(groups) {
  const series = groups.filter((g) => g.section === 2);
  // Hung in turn — one from each series, then the next from each — so the
  // series are mixed on the wall rather than in blocks.
  const order = [];
  const longest = Math.max(0, ...series.map((g) => g.photos.length + (g.cover ? 1 : 0)));
  for (let i = 0; i < longest; i++) {
    for (const g of series) {
      const all = g.cover ? [g.cover, ...g.photos] : g.photos;
      if (all[i]) order.push([g, all[i]]);
    }
  }
  const tiles = order.map(([g, p], i) => [
    `      <button class="tile${p.tall ? " tall" : ""}" type="button" data-g="${g.slug}" data-base="${p.base}" data-widths="${p.widths.join(",")}" data-jpg="${p.jpg}" data-w="${p.w}" data-h="${p.h}">`,
    picture(p, { sizes: "(max-width: 820px) 31vw, 12vw", lazy: i >= 12, indent: "        " }),
    "      </button>",
  ].join("\n"));
  return shell({
    title: `${sections[2].title} — ${site.name}`, desc: site.description, counter: true, bodyClass: "studies-page",
    nav: navBlock(groups, "fleeting"), scripts: ["wall.js"],
    main: `    <!-- Every photograph in ${sections[2].title}; data-g is its series. -->
    <div class="wall-window">
    <div class="wall" id="wall">
${tiles.join("\n")}
    </div>
    </div>

    <!-- One photograph, large. wall.js fills it from the tile that was clicked.
         Esc, or any name in the menu, returns to the wall. -->
    <div class="single" id="single" hidden>
      <!-- The arrows show on a phone only. -->
      <button class="nav-arrow up" type="button" aria-label="Previous photograph"><span aria-hidden="true"></span></button>
      <picture>
        <source type="image/avif">
        <source type="image/webp">
        <img alt="">
      </picture>
      <button class="nav-arrow down" type="button" aria-label="Next photograph"><span aria-hidden="true"></span></button>
      <button class="zone prev" type="button" aria-label="Previous photograph"></button>
      <button class="zone next" type="button" aria-label="Next photograph"></button>
    </div>`,
  });
}

function between(text, start, end, body, file) {
  const a = text.indexOf(start), b = text.indexOf(end);
  if (a < 0 || b < 0) { log(`  ${file}: no ${start.trim()} marker, left as it is`); return text; }
  return text.slice(0, a) + body + text.slice(b + end.length);
}

// ---------------------------------------------------------------- main ----
const groups = await findGroups();
try {
  for (const g of groups) { log(`${g.dir}`); await processGroup(g); }
} catch (e) {
  if (!(e instanceof OutOfTime)) throw e;
  await saveCache();
  log("\nout of time — not finished; run again to carry on. Pages not written.");
  process.exit(2);
}

// Forget folders that no longer exist.
for (const k of Object.keys(cache)) {
  if (!groups.some((g) => k.startsWith(g.dir + "/")) && !hidden.some((h) => k.split("/")[0].endsWith("-" + h))) delete cache[k];
}
await saveCache();
// The mark at the top of the menu: 陳覺, from assets/icons/mark.svg.
const markSrc = await fs.readFile(path.join(ROOT, "assets/icons/mark.svg"), "utf8");
MARK = `<svg class="mark" viewBox="0 0 200 100" role="img" aria-label="陳覺" focusable="false">${(markSrc.match(/<path[^>]*\/>/g) || []).join("")}</svg>`;

const write = async (file, text) => {
  const p = path.join(ROOT, file);
  const old = await fs.readFile(p, "utf8").catch(() => null);
  if (old !== text) { await fs.writeFile(p, text); log(`wrote ${file}`); }
};

await write(sections[1].page, projectsPage(groups));
await write(sections[2].page, fleetingPage(groups));
const projectSlugs = new Set();
for (const g of groups.filter((g) => g.section === 1)) {
  projectSlugs.add(`${g.slug}.html`);
  await write(`${g.slug}.html`, projectPage(groups, g));
}
// A project page whose folder has gone, or is hidden, goes too.
for (const f of await fs.readdir(ROOT)) {
  if (!f.endsWith(".html") || projectSlugs.has(f)) continue;
  const text = await fs.readFile(path.join(ROOT, f), "utf8");
  if (text.includes(PROJECT_MARK)) { await fs.unlink(path.join(ROOT, f)); log(`removed ${f}: its folder is gone or hidden`); }
}

// Hand-written pages: only the menu, and the hero on the home page.
for (const [file, kind] of [["index.html", "home"], ["about.html", "about"], ["shop.html", "shop"]]) {
  let text = await fs.readFile(path.join(ROOT, file), "utf8");
  text = text.replace(/<svg class="mark"[\s\S]*?<\/svg>/, MARK);
  text = between(text, "      <!-- nav start", "<!-- nav end -->\n", navBlock(groups, kind), file);
  if (file === "index.html") {
    const home = groups.find((g) => g.section === 0);
    const hero = home && (home.cover || home.photos[0]);
    if (hero) text = between(text, "<!-- build:hero start -->", "<!-- build:hero end -->",
      "<!-- build:hero start -->\n" + picture(hero, { sizes: "(max-width: 820px) 200vw, (max-height: 500px) 100vw, max(72vw, 140vh)" }).replace("<img ", '<img fetchpriority="high" ') + "\n      <!-- build:hero end -->", file);
  }
  await write(file, text);
}

